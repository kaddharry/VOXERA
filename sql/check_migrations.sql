checked AS (
  SELECT e.*,
    CASE e.kind
      WHEN 'extension' THEN EXISTS (SELECT 1 FROM pg_extension x WHERE x.extname = e.name)
      WHEN 'table'     THEN EXISTS (SELECT 1 FROM information_schema.tables t
                                    WHERE t.table_schema = 'public' AND lower(t.table_name) = lower(e.tbl))
      WHEN 'column'    THEN EXISTS (SELECT 1 FROM information_schema.columns c
                                    WHERE c.table_schema = 'public' AND lower(c.table_name) = lower(e.tbl)
                                      AND lower(c.column_name) = lower(e.name))
      WHEN 'function'  THEN EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                                    WHERE n.nspname = 'public' AND lower(p.proname) = lower(e.name))
      WHEN 'policy'    THEN EXISTS (SELECT 1 FROM pg_policies pl
                                    WHERE pl.schemaname = 'public' AND lower(pl.tablename) = lower(e.tbl)
                                      AND pl.policyname = e.name)
    END AS present
  FROM expected e
)
SELECT
  migration,
  CASE WHEN bool_and(present) THEN 'OK' ELSE 'MISSING' END AS status,
  count(*)                              AS checks,
  count(*) FILTER (WHERE NOT present)   AS missing,
  string_agg(
    CASE WHEN NOT present THEN
      CASE kind WHEN 'column' THEN 'column ' || tbl || '.' || name
                WHEN 'table'  THEN 'table ' || tbl
                WHEN 'policy' THEN 'policy "' || name || '" on ' || tbl
                ELSE kind || ' ' || name END
    END, ', ' ORDER BY kind, tbl, name)  AS what_is_missing
FROM checked
GROUP BY migration
ORDER BY substring(migration from 2)::int;
